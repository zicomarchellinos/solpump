function translateError(msg) {
  if (typeof msg !== 'string' || !msg) return msg;
  if (currentLang === 'id') return msg;
  for (const [needle, key] of SERVER_ERROR_MAP) {
    if (msg.includes(needle)) return translate(key);
  }
  return msg;
}

function applyStaticI18n() {
  if (typeof document === 'undefined') return;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = translate(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = translate(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', translate(el.dataset.i18nTitle));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', translate(el.dataset.i18nPlaceholder));
  });
}

function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  currentLang = lang;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    // Storage unavailable — the choice just doesn't persist.
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = LANG_HTML_ATTR[lang];
    document.title = translate('pageTitle');
    const meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute('content', translate('pageDesc'));
    applyStaticI18n();
  }
  // The caller (app.js) re-renders the header + current view so dynamic
  // strings switch too; the language switcher calls setLang then route().
}

// Expose globals for app.js / solana.js and the smoke tests.
if (typeof window !== 'undefined') {
  window.STRINGS = STRINGS;
  window.getLang = getLang;
  window.setLang = setLang;
  window.translate = translate;
  window.t = translate;
  window.applyStaticI18n = applyStaticI18n;
  window.translateError = translateError;
}

// Apply the stored language to the static shell immediately (this script
// loads at the end of <body>, so the shell already exists).
setLang(currentLang);

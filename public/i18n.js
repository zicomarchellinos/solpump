const LANGS = ['id', 'en', 'zh'];
const LANG_STORAGE_KEY = 'solpump-lang';
const LANG_HTML_ATTR = { id: 'id', en: 'en', zh: 'zh-CN' };

function storedLang() {
  try {
    const v = localStorage.getItem(LANG_STORAGE_KEY);
    return LANGS.includes(v) ? v : 'id';
  } catch {
    return 'id';
  }
}

let currentLang = storedLang();

function getLang() {
  return currentLang;
}

// Translate a key, interpolating {placeholders} from `vars` (an object).
// Falls back to Indonesian, then to the key itself. When `vars` is a
// string it is the fallback text (used by solana.js when this file is not
// loaded in the test sandbox — the Indonesian string there).
function translate(key, vars) {
  const dict = STRINGS[currentLang] || STRINGS.id;
  let str = dict[key];
  if (str === undefined) str = STRINGS.id[key];
  if (str === undefined) return typeof vars === 'string' ? vars : key;
  if (vars && typeof vars === 'object') {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split(`{${k}}`).join(String(v));
    }
  }
  return str;
}

